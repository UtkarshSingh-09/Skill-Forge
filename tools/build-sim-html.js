const fs = require('fs');
const path = require('path');

const templatePath = path.join(__dirname, '../assets/sim/index.template.html');
const bundlePath = path.join(__dirname, '../assets/sim/bundle.js');
const outputHtmlPath = path.join(__dirname, '../assets/sim/index.html');
const outputTsPath = path.join(__dirname, '../assets/sim/simHtml.ts');

const template = fs.readFileSync(templatePath, 'utf8');
const bundle = fs.readFileSync(bundlePath, 'utf8');

// Use a function as second argument to avoid treating $ in bundle.js as replacement patterns
const inlined = template.replace(
  '<script src="./bundle.js"></script>',
  () => `<script>\n${bundle}\n</script>`
);

fs.writeFileSync(outputHtmlPath, inlined, 'utf8');

const tsContent = `// Auto-generated by tools/build-sim-html.js — DO NOT EDIT DIRECTLY
// Contains complete, offline inlined avr8js + @wokwi/elements simulator
export const SIMULATOR_HTML: string = ${JSON.stringify(inlined)};
`;

fs.writeFileSync(outputTsPath, tsContent, 'utf8');

console.log('Successfully built inlined simulator HTML & simHtml.ts!');
console.log('HTML size:', (inlined.length / 1024).toFixed(1), 'KB');
